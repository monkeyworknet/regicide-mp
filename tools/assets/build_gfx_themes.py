#!/usr/bin/env python3
"""Build the two extra card themes (and their table furniture) from Card_Game_GFX.zip.

Sources (800x1080 RGBA PNGs, one per card):
  Cards/simplecard_<suit>_<n>.png    clean deck    -> theme "simple"
  Cards/card backs/<colour>_back_<variant>.png     -> selectable backs
  Chips/chips_flat_<colour>.png                  -> pile counters

Outputs into src/regicide/server/web/img/:
  simple/<cardid>.webp
  backs/<colour>.webp
  furniture/die_<n>.webp, furniture/chip.webp
  The registry (web/data/themes.json) is generated by build_theme_registry.py

Usage:
  python3 tools/assets/build_gfx_themes.py
  python3 tools/assets/build_gfx_themes.py --check
"""
from __future__ import annotations

import argparse
import json
import pathlib
import shutil
import sys
import zipfile

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[2]
ZIP = ROOT / "artifacts/Card_Game_GFX.zip"
WORK = ROOT / "build/gfx"
OUT = ROOT / "src/regicide/server/web/img"

FACE_WIDTH = 400       # hand cards are <= 118 css px, enemy <= 168: 400 is 2x-plus
QUALITY = 80
# The ornamental deck spells suits plural ("clubs"), the simple deck singular ("club").
SUIT_TOKENS = {"C": ("clubs", "club"), "D": ("diamond", "diamonds"), "H": ("heart", "hearts"), "S": ("spade", "spades")}
RANK_LABEL = {1: "A", 11: "J", 12: "Q", 13: "K"}
BACK_COLOURS = ["black", "blue", "green", "orange", "purple", "red"]
BACK_VARIANT = "suits_dark"


def unzip() -> pathlib.Path:
    if not ZIP.exists():
        raise SystemExit(f"missing {ZIP}")
    if not WORK.exists():
        WORK.mkdir(parents=True)
        with zipfile.ZipFile(ZIP) as zf:
            zf.extractall(WORK)
    return WORK


def card_id(letter: str, n: int) -> str:
    return f"{RANK_LABEL.get(n, str(n))}{letter}"


def convert(src: pathlib.Path, dest: pathlib.Path, width: int = FACE_WIDTH) -> int:
    dest.parent.mkdir(parents=True, exist_ok=True)
    with Image.open(src) as im:
        im = im.convert("RGBA")
        height = round(im.height * width / im.width)
        im = im.resize((width, height), Image.LANCZOS)
        im.save(dest, "WEBP", quality=QUALITY, method=6)
    return dest.stat().st_size


def sources_for(prefix: str) -> dict[str, pathlib.Path]:
    out: dict[str, pathlib.Path] = {}
    for letter, tokens in SUIT_TOKENS.items():
        for n in range(1, 14):
            for token in tokens:
                path = WORK / "Cards" / f"{prefix}_{token}_{n}.png"
                if path.exists():
                    out[card_id(letter, n)] = path
                    break
    jokers = {
        "J1": WORK / "Cards" / f"{prefix}_joker_red.png",
        "J2": WORK / "Cards" / f"{prefix}_joker_black.png",
    }
    for cid, path in jokers.items():
        if path.exists():
            out[cid] = path
    return out


def build(check: bool) -> int:
    themes = {"simple": "simplecard"}
    plan: dict[str, dict[str, pathlib.Path]] = {}

    if check:
        missing = []
        for theme in ("simple",):
            faces = list((OUT / theme).glob("*.webp"))
            if len(faces) != 54:
                missing.append(f"{theme} ({len(faces)}/54)")
        chips = [c for c in ("black", "blue", "green", "orange", "purple", "red", "white")
                 if (OUT / "furniture" / f"chip_{c}.webp").exists()]
        if len(chips) < 7:
            missing.append(f"chips ({len(chips)}/7)")
        if missing:
            print("missing gfx assets: " + ", ".join(missing), file=sys.stderr)
            return 1
        total = sum(p.stat().st_size for p in (OUT / "simple").glob("*.webp"))
        print(f"gfx theme: simple present ({total/1024/1024:.2f} MB)")
        return 0

    unzip()
    total = 0
    counts = {"faces": 0, "backs": 0, "chips": 0}

    for theme, prefix in themes.items():
        files = sources_for(prefix)
        if len(files) != 54:
            print(f"{theme}: found {len(files)} faces, want 54", file=sys.stderr)
            return 1
        for cid, src in sorted(files.items()):
            total += convert(src, OUT / theme / f"{cid.lower()}.webp")
            counts["faces"] += 1
        print(f"{theme}: {len(files)} faces")

    for colour in BACK_COLOURS:
        src = WORK / "Cards" / "card backs" / f"{colour}_back_{BACK_VARIANT}.png"
        if not src.exists():
            src = WORK / "Cards" / "card backs" / f"{colour}_back_plain.png"
        if src.exists():
            total += convert(src, OUT / "backs" / f"{colour}.webp", width=300)
            counts["backs"] += 1
    print(f"backs: {counts['backs']}")

    # No dice: the counter style draws the number on a flat poker chip, and the
    # dice assets were never referenced by the UI.
    # One flat chip per colour: the pile counters draw the count on top of these.
    chips = 0
    for colour in ("black", "blue", "green", "orange", "purple", "red", "white"):
        src = WORK / "Chips" / f"chips_flat_{colour}.png"
        if src.exists():
            total += convert(src, OUT / "furniture" / f"chip_{colour}.webp", width=96)
            chips += 1
    print(f"chips: {chips}")

    print(f"wrote theme assets ({total/1024/1024:.2f} MB)")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    if args.check:
        return build(True)
    if not WORK.exists() and not ZIP.exists():
        print("no Card_Game_GFX.zip and no extracted work dir; skipping theme build", file=sys.stderr)
        return 1
    return build(False)


if __name__ == "__main__":
    raise SystemExit(main())
