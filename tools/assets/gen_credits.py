#!/usr/bin/env python3
"""Regenerate the committed-asset provenance table in docs/CREDITS.md.

Reads `git ls-files` (plus untracked files that will be committed) and rewrites the
table between the markers so `check_credits.sh` stays green without hand editing.
"""
from __future__ import annotations

import pathlib
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[2]
CREDITS = ROOT / "docs/CREDITS.md"
START = "## Committed asset provenance"
END = "## Not committed"

SOURCES = (
    ("/img/simple/", "`artifacts/Card_Game_GFX.zip` → WebP",
     "supplied for this non-commercial fan build"),
    ("/img/backs/", "`artifacts/Card_Game_GFX.zip` card backs → WebP",
     "supplied for this non-commercial fan build"),
    ("/img/furniture/", "`artifacts/Card_Game_GFX.zip` dice/chips → WebP",
     "supplied for this non-commercial fan build"),
    ("/img/gfx/", "generated by `tools/assets/build_gfx_themes.py`", "our own manifest"),
    ("/img/jokers/", "`tools/assets/build_joker_set.py` (supplied joker card + deck joker art + a 4 x 4 reference sheet)",
     "joker designs belong to their own publishers (Dreamstime stock preview, Bicycle, etc.); private, non-commercial use"),
    ("/img/pokemon/", "`artifacts/Pokemon_RageIced_*_of_4.pdf` → `pdfimages` → WebP",
     "fan re-theme by Wil Su; Pokémon © Nintendo/Game Freak/Creatures; private, non-commercial"),
    ("/img/official/", "`artifacts/reg-official.png` (uncut 9 x 6 sheet) and `artifacts/reg-official-back.png` → `tools/assets/build_official.py` → WebP",
     "official Regicide card art © Badgers from Mars, art by Sketchgoblin; non-commercial fan build"),
)


def describe(path: str) -> tuple[str, str]:
    for needle, src, note in SOURCES:
        if needle in path:
            if path.endswith("back.webp") or "/backs/" in path:
                return src, note + (" — card back" if "back" in path else "")
            return src, note
    if "/sfx/synth_" in path:
        return "synthesised by `tools/assets/synth_sfx.py`", "our own work (numpy → ffmpeg)"
    if "/sfx/" in path:
        return ("`artifacts/CrispCards_Free_Sampler.zip` → `OGG/`",
                "Crisp Cards sampler licence: embed-only, no pack redistribution; credit Anipixels")
    if path.endswith("cardtext.json"):
        return "generated by `tools/assets/gen_cardtext.py`", "our own work"
    if path.endswith("audio.json"):
        return "authored", "our own work"
    return "our own work", "authored"


def main() -> int:
    tracked = subprocess.run(["git", "ls-files", "src/regicide/server/web"], cwd=ROOT,
                             capture_output=True, text=True).stdout.split()
    untracked = subprocess.run(["git", "ls-files", "--others", "--exclude-standard", "src/regicide/server/web"],
                               cwd=ROOT, capture_output=True, text=True).stdout.split()
    assets = sorted(set(p for p in tracked + untracked
                        if p.startswith(("src/regicide/server/web/img/", "src/regicide/server/web/sfx/",
                                         "src/regicide/server/web/data/"))))
    rows = []
    for path in assets:
        src, note = describe(path)
        rows.append(f"| `{path}` | {src} | {note} |")

    text = CREDITS.read_text()
    head = text.split(START)[0].rstrip()
    tail = END + text.split(END, 1)[1] if END in text else END + "\n"
    body = (
        f"{START}\n\nEvery file below is in git and appears here; `tools/assets/check_credits.sh` enforces it. "
        f"Regenerate with `python3 tools/assets/gen_credits.py`.\n\n"
        f"| File | Source | Attribution / constraint |\n|---|---|---|\n" + "\n".join(rows) + "\n\n"
    )
    CREDITS.write_text(head + "\n\n" + body + tail)
    print(f"credits: {len(rows)} asset rows")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
